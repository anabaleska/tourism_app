create table users (
    user_id varchar(255) not null,
    username varchar(255),
    email varchar(255),
    password varchar(255),
    role varchar(255) check (role in ('USER', 'MODERATOR', 'ADMIN')),
    constraint pk_users primary key (user_id),
    constraint uk_users_username unique (username),
    constraint uk_users_email unique (email)
);

create table places (
    place_id varchar(255) not null,
    name varchar(255) not null,
    category varchar(255),
    type varchar(255),
    place varchar(255),
    municipality varchar(255),
    lat double precision,
    lng double precision,
    rating double precision,
    price integer,
    time_to_visit integer,
    tags varchar(255),
    description varchar(255),
    name_normalized varchar(255),
    model_text varchar(255),
    image_url varchar(255),
    constraint pk_places primary key (place_id)
);

create table interactions (
    id bigint generated by default as identity,
    user_id varchar(255),
    place_id varchar(255),
    interaction integer,
    constraint pk_interactions primary key (id),
    constraint fk_interactions_user foreign key (user_id) references users (user_id),
    constraint fk_interactions_place foreign key (place_id) references places (place_id),
    constraint uk_interactions_user_place unique (user_id, place_id)
);
